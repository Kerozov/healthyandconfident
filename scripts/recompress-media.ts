#!/usr/bin/env bun
export {};

/**
 * Shrinks the photos that went into the `media` bucket before uploads were
 * compressed in the browser (`lib/admin/compress-image.ts`).
 *
 *   bun scripts/recompress-media.ts          # show what it would do
 *   bun scripts/recompress-media.ts --write  # upload the small copies
 *
 * Those are 2–5 MB PNGs, and `/files` pulls each one from Supabase again on
 * every Vercel cache miss — a few of them were most of the organisation's
 * cached egress. They are also over the 2 MB Data Cache limit, so `/files`
 * can't keep them.
 *
 * Each file is re-encoded as WebP at most 2000 px, the same as a new upload,
 * and stored under a NEW key next to the old one. Overwriting in place does not
 * work on the Free plan: without Smart CDN, Supabase's CDN keeps serving (and
 * billing) the old bytes for as long as the year-long cache-control allows.
 * Nothing is overwritten or deleted, so links in emails already sent keep
 * working.
 *
 * `--write` saves `media-recompress/rewrite-urls.sql`, which points every
 * reference in the database at the new keys. Run it in the SQL editor
 * afterwards.
 *
 * Files under 400 KB, GIFs, PDFs and anything that would not shrink by at
 * least a third are left alone.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { posix } from "node:path";
import sharp from "sharp";

const BUCKET = "media";
const MAX_SIDE = 2000;
const QUALITY = 82;
const MIN_BYTES = 400 * 1024;
const MIN_SAVING = 1 / 3;
const OUT_DIR = "media-recompress";

const write = process.argv.includes("--write");

const url = (process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL || "").replace(/\/$/, "");
const key = (process.env.SUPABASE_SERVICE_ROLE_KEY || "").trim();

if (!url || !key) {
  console.error("Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in .env");
  process.exit(1);
}

const { createClient } = await import("@supabase/supabase-js");
const supabase = createClient(url, key, {
  auth: { persistSession: false, autoRefreshToken: false },
});

type Entry = { path: string; size: number; mimetype: string };

async function listFolder(prefix: string): Promise<Entry[]> {
  const out: Entry[] = [];
  for (let offset = 0; ; offset += 100) {
    const { data, error } = await supabase.storage
      .from(BUCKET)
      .list(prefix, { limit: 100, offset });
    if (error) throw error;
    if (!data?.length) break;
    for (const item of data) {
      const path = prefix ? `${prefix}/${item.name}` : item.name;
      if (!item.id) {
        out.push(...(await listFolder(path)));
      } else {
        out.push({
          path,
          size: Number(item.metadata?.size ?? 0),
          mimetype: String(item.metadata?.mimetype ?? ""),
        });
      }
    }
    if (data.length < 100) break;
  }
  return out;
}

const mb = (n: number) => `${(n / 1048576).toFixed(2)} MB`;

/** `'…'` with quotes doubled — the paths are UUID keys, but never trust that. */
const sqlString = (s: string) => `'${s.replaceAll("'", "''")}'`;

/**
 * One statement that swaps `/media/<old>` for `/media/<new>` in every text,
 * varchar, json, jsonb and text[] column of the public schema. Matching on the
 * key covers both `/files/media/…` and raw Storage URLs.
 */
function rewriteSql(pairs: [string, string][]): string {
  const values = pairs
    .map(([from, to]) => `    (${sqlString(`/${BUCKET}/${from}`)}, ${sqlString(`/${BUCKET}/${to}`)})`)
    .join(",\n");

  return `-- Generated by scripts/recompress-media.ts on ${new Date().toISOString()}
do $$
declare
  m record;
  c record;
  n bigint;
  total bigint := 0;
begin
  for m in
    select * from (values
${values}
    ) as v(old_key, new_key)
  loop
    for c in
      select a.attrelid::regclass as tbl, a.attname as col,
             format_type(a.atttypid, a.atttypmod) as typ
      from pg_attribute a
      join pg_class r on r.oid = a.attrelid
      join pg_namespace s on s.oid = r.relnamespace
      where s.nspname = 'public' and r.relkind = 'r'
        and a.attnum > 0 and not a.attisdropped
        and a.atttypid in ('text'::regtype, 'varchar'::regtype, 'json'::regtype,
                           'jsonb'::regtype, 'text[]'::regtype)
    loop
      execute format(
        'update %s set %I = replace(%I::text, $1, $2)::%s where strpos(%I::text, $1) > 0',
        c.tbl, c.col, c.col, c.typ, c.col
      ) using m.old_key, m.new_key;
      get diagnostics n = row_count;
      total := total + n;
    end loop;
  end loop;
  raise notice 'media references rewritten: %', total;
end $$;
`;
}

const candidates = (await listFolder("")).filter(
  (f) =>
    f.size >= MIN_BYTES &&
    f.mimetype.startsWith("image/") &&
    f.mimetype !== "image/gif",
);

let before = 0;
let after = 0;
const moved: [string, string][] = [];

for (const file of candidates) {
  const { data: blob, error } = await supabase.storage.from(BUCKET).download(file.path);
  if (error || !blob) {
    console.error(`skip ${file.path}: ${error?.message ?? "no data"}`);
    continue;
  }

  const input = Buffer.from(await blob.arrayBuffer());
  const output = await sharp(input)
    .rotate()
    .resize(MAX_SIDE, MAX_SIDE, { fit: "inside", withoutEnlargement: true })
    .webp({ quality: QUALITY })
    .toBuffer();

  if (output.length > input.length * (1 - MIN_SAVING)) {
    console.log(`keep ${file.path}: ${mb(input.length)} → ${mb(output.length)} is not worth it`);
    continue;
  }

  const target = posix.join(posix.dirname(file.path), `${crypto.randomUUID()}.webp`);
  before += input.length;
  after += output.length;
  console.log(`${write ? "copy" : "would copy"} ${file.path} → ${target}: ${mb(input.length)} → ${mb(output.length)}`);

  if (!write) continue;

  const { error: upErr } = await supabase.storage.from(BUCKET).upload(target, output, {
    upsert: false,
    contentType: "image/webp",
    cacheControl: "31536000",
  });
  if (upErr) {
    console.error(`  failed: ${upErr.message}`);
    continue;
  }
  moved.push([file.path, target]);
}

console.log(`\n${candidates.length} candidates, ${mb(before)} → ${mb(after)}${write ? "" : " (dry run, add --write)"}`);

if (write && moved.length) {
  await mkdir(OUT_DIR, { recursive: true });
  await writeFile(`${OUT_DIR}/mapping.json`, JSON.stringify(Object.fromEntries(moved), null, 2));
  await writeFile(`${OUT_DIR}/rewrite-urls.sql`, rewriteSql(moved));
  console.log(`\nNext: run ${OUT_DIR}/rewrite-urls.sql in the Supabase SQL editor.`);
}
