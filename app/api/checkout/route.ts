import { NextRequest, NextResponse, after } from "next/server";
import { isLocale, type Locale } from "@/i18n/config";
import {
  createProductCheckoutSession,
  createGuideCheckoutSession,
  createPlacementCheckoutSession,
  type CheckoutSessionResult,
} from "@/lib/stripe/create-checkout";
import { createBlackFridayCheckoutSession } from "@/lib/black-friday/checkout";
import { recordContactEvent } from "@/lib/contacts/events";
import { getContactById } from "@/lib/contacts/ensure";
import { schedulePrePaymentReminders } from "@/lib/contacts/reminders";
import { sendMetaEvent } from "@/lib/meta/capi";
import { fbcFromClickId, metaUserFromRequest } from "@/lib/meta/request";

export async function POST(request: NextRequest) {
  try {
    const body = (await request.json()) as {
      productIds?: string[];
      guideIds?: string[];
      placementKey?: string;
      /** A Black Friday offer: one discounted item or a bundle. */
      blackFriday?: { itemKey?: string; bundleId?: string; earlyKey?: string };
      locale?: string;
      contactId?: string;
      /** Generated by the browser pixel so Meta deduplicates the event pair. */
      metaEventId?: string;
      fbp?: string | null;
      fbc?: string | null;
      fbclid?: string | null;
    };

    const productIds = body.productIds?.filter(Boolean) ?? [];
    const guideIds = body.guideIds?.filter(Boolean) ?? [];
    const placementKey = body.placementKey?.trim() ?? "";
    const blackFriday =
      body.blackFriday && (body.blackFriday.itemKey || body.blackFriday.bundleId)
        ? {
            itemKey: String(body.blackFriday.itemKey ?? "").trim().slice(0, 120) || undefined,
            bundleId: String(body.blackFriday.bundleId ?? "").trim().slice(0, 64) || undefined,
            earlyKey: String(body.blackFriday.earlyKey ?? "").trim().slice(0, 64) || undefined,
          }
        : null;
    const locale = body.locale && isLocale(body.locale) ? (body.locale as Locale) : "bg";
    const contactId = body.contactId?.trim() || request.cookies.get("hc_contact")?.value?.trim();

    const selectedKinds =
      Number(productIds.length > 0) +
      Number(guideIds.length > 0) +
      Number(Boolean(placementKey)) +
      Number(Boolean(blackFriday));
    if (selectedKinds > 1) {
      return NextResponse.json(
        { message: "Cannot checkout mixed item types together" },
        { status: 400 },
      );
    }

    let contactEmail: string | null = null;
    let contactName: string | null = null;

    if (contactId && (productIds.length > 0 || blackFriday)) {
      const contact = await getContactById(contactId);
      if (contact) {
        contactEmail = contact.email;
        contactName = contact.name;
        void recordContactEvent({
          contactId,
          eventType: "checkout_started",
          source: "site",
          metadata: blackFriday
            ? { black_friday: blackFriday.bundleId ?? blackFriday.itemKey, locale }
            : { product_ids: productIds, locale },
        }).catch(() => {});
        if (contact.payment_status !== "paid") {
          void schedulePrePaymentReminders(contact, locale).catch(() => {});
        }
      }
    }

    if (productIds.length === 0 && guideIds.length === 0 && !placementKey && !blackFriday) {
      return NextResponse.json({ message: "No items selected" }, { status: 400 });
    }

    const browser = metaUserFromRequest(request);
    const fbp = body.fbp?.trim() || browser.fbp || null;
    const fbc =
      body.fbc?.trim() || browser.fbc || fbcFromClickId(body.fbclid) || null;
    const isGuide = guideIds.length > 0;
    let itemIds = placementKey
      ? [placementKey]
      : isGuide
        ? guideIds
        : productIds;
    // Pixel cookies ride along in session metadata so the webhook can attribute
    // the Purchase event back to the ad click.
    const tracking = {
      fbp,
      fbc,
      userAgent: browser.clientUserAgent,
    };
    let session: CheckoutSessionResult;
    if (blackFriday) {
      const offer = await createBlackFridayCheckoutSession(blackFriday, locale, contactId, tracking);
      session = offer;
      itemIds = offer.itemKeys;
    } else {
      session = placementKey
        ? await createPlacementCheckoutSession(placementKey, locale, contactId, tracking)
        : isGuide
          ? await createGuideCheckoutSession(guideIds, locale, contactId, tracking)
          : await createProductCheckoutSession(productIds, locale, contactId, tracking);
    }

    // Server half of InitiateCheckout — exact Stripe amount, survives ad blockers.
    // `after` keeps the redirect instant while the request stays alive for Meta.
    const referer = request.headers.get("referer");
    after(async () => {
      await sendMetaEvent({
        eventName: "InitiateCheckout",
        eventId: body.metaEventId?.trim() || null,
        eventSourceUrl: referer,
        source: "server",
        user: {
          ...browser,
          fbp,
          fbc,
          email: contactEmail,
          firstName: contactName?.split(/\s+/)[0] ?? null,
          externalId: contactId ?? null,
        },
        custom: {
          value: session.amountCents != null ? session.amountCents / 100 : null,
          currency: session.currency,
          contentIds: itemIds,
          contentType: "product",
          numItems: itemIds.length,
        },
      });
    });

    return NextResponse.json({ url: session.url });
  } catch (err) {
    const message = err instanceof Error ? err.message : "Checkout failed";
    return NextResponse.json({ message }, { status: 400 });
  }
}
